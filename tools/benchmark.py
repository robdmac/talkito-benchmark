#!/usr/bin/env python3
"""Pick which models to benchmark, run them, and open the result.

    python3 tools/benchmark.py

Everything is ticked by default. Toggle with numbers or names, then press Enter to start. Each
model prints its own line as it finishes, and the run ends with an `open` command for the page.

Four things this handles that a plain loop over run_benchmark_sweep.py does not:

  replacement    The page merges every state file it globs, weighting by sample count, so writing
                 a fresh state alongside the old one averages the new run with the old instead of
                 replacing it. Selected models have their units removed from every file the page
                 reads before anything runs.

  --repeat       The runner defaults to 3, and the existing states were built at 1. A unit run at
                 3 records three phrases as total=9, and since coverage is summed from `total`, it
                 counts them three times and can push a row past 84.

  disclosure     Three runtimes speak an AI disclosure before the text. It has to be stripped
                 before scoring or they read ~70 points too high, and the flag is per-run, so
                 those models are run in their own pass rather than with everyone else.

  timing         RTF is wall-clock and nothing else in the table is. Models run one at a time, and
                 the run refuses to start if something heavy is already going.

Add --yes to skip the picker and run everything, for cron or a second terminal.
"""

import argparse
import json
import os
import re
import shutil
import subprocess
import sys
import time

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)          # the benchmark repo
sys.path.insert(0, HERE)
from paths import TALKITO             # the talkito checkout being measured
PAGE_HTML = os.environ.get("TTS_BENCHMARK_PAGE",
                           os.path.join(REPO, "tts-benchmark.html"))
EXPORT_ZIP = os.path.join(REPO, "tts-benchmark-export.zip")
STATE = os.path.join(HERE, "sweep_rerun.json")

# Runtimes that speak "this audio was generated by artificial intelligence" before the text.
DISCLOSURE = {"fastpitch", "bananamind-tts", "parler-tts"}


def page_state_files():
    """The state files build_benchmark_page.py merges, read from the page builder itself.

    Hardcoding this list would drift the moment the glob there changes, and the failure is silent:
    units get purged from the files this script knows about, the page reads one it does not, and
    the old measurements reappear averaged into the new ones.
    """
    src = open(os.path.join(HERE, "build_benchmark_page.py")).read()
    block = re.search(r"STATES = sorted\((.*?)\n\s*if ", src, re.S).group(1)
    patterns = re.findall(r'"([^"]+\.json)"', block)
    import glob
    files = []
    for pattern in patterns:
        files += glob.glob(os.path.join(HERE, pattern))
    return sorted(f for f in files if "partial" not in f and "_r3" not in f)


def available():
    """Providers that can be benchmarked and would appear in the table, with recorded cost."""
    ns = {}
    sweep_src = open(os.path.join(HERE, "run_benchmark_sweep.py")).read()
    exec(re.search(r"^PROVIDER_META = \{.*?^\}$", sweep_src, re.S | re.M).group(0), ns)
    page_src = open(os.path.join(HERE, "build_benchmark_page.py")).read()
    page_ns = {}
    exec(re.search(r"^META = \{.*?^\}$", page_src, re.S | re.M).group(0), page_ns)
    exec(re.search(r"^EXCLUDED = \{.*?\}$", page_src, re.S | re.M).group(0), page_ns)
    exec(re.search(r"^EXCLUDED_PREFIXES = \(.*?\)$", page_src, re.S | re.M).group(0), page_ns)

    names = (set(ns["PROVIDER_META"]) & set(page_ns["META"])) - page_ns["EXCLUDED"]
    names = {n for n in names if not n.startswith(page_ns["EXCLUDED_PREFIXES"])}

    # Previous runs are the only honest source for how long this takes; a model never yet
    # measured shows "?" rather than a guess.
    spent = {}
    for path in page_state_files():
        for key, unit in json.load(open(path)).get("units", {}).items():
            if "error" in unit:
                continue
            spent.setdefault(key.split("|")[0], 0.0)
            spent[key.split("|")[0]] += unit.get("seconds", 0.0)
    return sorted((n, spent.get(n)) for n in names)


def pick(models):
    """Arrow-key checklist, everything ticked. Returns the chosen names.

    Matches talkito's own menus (cli.py show_interactive_menu): raw mode, escape sequences for the
    arrows, and a redraw that walks the cursor back up rather than clearing the screen, so the
    scrollback above the menu survives.

    Falls back to the typed form when stdin is not a terminal, which is what cron and a piped
    invocation get. The fallback also refuses to treat EOF as confirmation: piping input ends in
    EOF, and reading that as "yes" once started a multi-hour run that deleted the measurements it
    was replacing.
    """
    chosen = {n for n, _ in models}
    if not sys.stdin.isatty():
        return _pick_typed(models, chosen)

    import termios
    import tty

    def get_key():
        fd = sys.stdin.fileno()
        old = termios.tcgetattr(fd)
        try:
            tty.setraw(fd)
            key = sys.stdin.read(1)
            if key == "\x1b":
                key += sys.stdin.read(2)
            return key
        finally:
            termios.tcsetattr(fd, termios.TCSADRAIN, old)

    selected = 0
    # The list is longer than most terminals, so it scrolls with the cursor rather than printing
    # forty rows on every keypress.
    window = max(5, min(len(models), (shutil.get_terminal_size((80, 24)).lines - 8)))
    top = 0
    drawn = 0

    def render(redraw=False):
        nonlocal top, drawn
        if selected < top:
            top = selected
        elif selected >= top + window:
            top = selected - window + 1
        if redraw and drawn:
            print(f"\033[{drawn}A", end="")

        total = sum(s for n, s in models if n in chosen and s)
        lines = ["", "  models to benchmark  (↑↓ move, space toggles, a=all, n=none, "
                     "Enter runs, q quits)", ""]
        for i in range(top, min(top + window, len(models))):
            name, secs = models[i]
            cursor = "➤" if i == selected else " "
            box = "x" if name in chosen else " "
            cost = f"{secs / 60:5.0f} min" if secs else "    ?   "
            lines.append(f"  {cursor} [{box}] {i + 1:>2}. {name:<22}{cost}")
        more = len(models) - (top + window)
        lines.append(f"      … {more} more below" if more > 0 else "")
        lines.append(f"  {len(chosen)} selected, about {total / 3600:.1f} h of synthesis")
        for line in lines:
            print(f"\033[2K{line}")
        drawn = len(lines)

    render()
    while True:
        key = get_key()
        if key == "\x1b[A":
            selected = (selected - 1) % len(models)
        elif key == "\x1b[B":
            selected = (selected + 1) % len(models)
        elif key == " ":
            chosen.symmetric_difference_update({models[selected][0]})
        elif key in ("a", "A"):
            chosen = {n for n, _ in models}
        elif key in ("n", "N"):
            chosen = set()
        elif key in ("\r", "\n"):
            print()
            return sorted(chosen)
        elif key in ("q", "Q", "\x03"):
            print()
            sys.exit(0)
        else:
            continue
        render(redraw=True)


def _pick_typed(models, chosen):
    """Typed fallback for a non-terminal stdin: numbers, ranges and substrings."""
    while True:
        print("\n  models to benchmark\n")
        total = 0.0
        for i, (name, secs) in enumerate(models, 1):
            on = name in chosen
            cost = f"{secs / 60:5.0f} min" if secs else "    ?   "
            if on and secs:
                total += secs
            print(f"   {i:>2}. [{'x' if on else ' '}] {name:<22}{cost}")
        print(f"\n  {len(chosen)} selected, about {total / 3600:.1f} h of synthesis")
        print("  numbers or names to toggle (ranges like 4-9), a=all, n=none, Enter=run, q=quit")
        try:
            reply = input("  > ").strip()
        except EOFError:
            sys.exit("\n  no confirmation, nothing run")
        if not reply:
            return sorted(chosen)
        if reply == "q":
            sys.exit(0)
        if reply == "a":
            chosen = {n for n, _ in models}
            continue
        if reply == "n":
            chosen = set()
            continue
        for token in reply.replace(",", " ").split():
            if re.fullmatch(r"\d+-\d+", token):
                lo, hi = (int(x) for x in token.split("-"))
                hits = [models[i - 1][0] for i in range(lo, hi + 1) if 1 <= i <= len(models)]
            elif token.isdigit() and 1 <= int(token) <= len(models):
                hits = [models[int(token) - 1][0]]
            else:
                hits = [n for n, _ in models if token in n]
                if not hits:
                    print(f"  no model matches {token!r}")
            for name in hits:
                chosen.symmetric_difference_update({name})

def busy():
    """True if something heavy is already running, since RTF is wall-clock sensitive."""
    out = subprocess.run(["ps", "-Ao", "command"], capture_output=True, text=True).stdout
    return [p for p in ("test_tts_asr_roundtrip", "run_benchmark_sweep", "crispasr")
            if p in out]


def purge(names):
    """Remove these providers' units from every state file the page reads."""
    removed = 0
    for path in page_state_files():
        state = json.load(open(path))
        units = state.get("units", {})
        drop = [k for k in units if k.split("|")[0] in names]
        if not drop:
            continue
        os.replace(path, path + ".bak")
        for key in drop:
            del units[key]
        json.dump(state, open(path, "w"))
        removed += len(drop)
    return removed


def report(name):
    """One line for a finished model, read back from the state it just wrote."""
    units = [v for k, v in json.load(open(STATE))["units"].items()
             if k.split("|")[0] == name and "error" not in v]
    total = sum(v["total"] for v in units)
    if not total:
        return f"  {name:<22} no result"
    passed = sum(v["passed"] for v in units)
    wer = sum(v["mean_wer"] * v["total"] for v in units) / total
    audio = sum(v.get("audio_seconds", 0) for v in units)
    synth = sum(v.get("synth_seconds", 0) for v in units)
    rtf = synth / audio if audio else 0
    return (f"  {name:<22}{passed:>3}/{total:<3} phrases   WER {wer:>5.1%}   "
            f"RTF {rtf:>5.2f}x")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--yes", action="store_true", help="run everything, no picker")
    ap.add_argument("--only", help="comma-separated models, no picker")
    ap.add_argument("--keep", action="store_true",
                    help="add to existing measurements instead of replacing them")
    args = ap.parse_args()

    models = available()
    if args.only:
        wanted = {s.strip() for s in args.only.split(",")}
        names = sorted(n for n, _ in models if n in wanted)
        missing = wanted - set(names)
        if missing:
            sys.exit(f"unknown model(s): {', '.join(sorted(missing))}")
    elif args.yes:
        names = [n for n, _ in models]
    else:
        names = pick(models)
    if not names:
        sys.exit("nothing selected")

    running = busy()
    if running:
        print(f"\n  warning: {', '.join(running)} already running. RTF is wall-clock and will "
              f"read high.")
        try:
            if input("  continue anyway? [y/N] ").strip().lower() != "y":
                sys.exit(0)
        except EOFError:
            # No terminal to ask. Declining is the safe reading: the warning exists because RTF is
            # wall-clock, and a scripted run that ignores it silently records inflated timings.
            sys.exit("  not a terminal, declining rather than measuring under load")

    if not args.keep:
        print(f"\n  removing previous measurements for {len(names)} model(s)...", flush=True)
        print(f"  {purge(set(names))} units removed (.bak written beside each state file)")

    print(f"\n  running {len(names)} model(s), one at a time\n")
    started = time.time()
    failed = []
    for i, name in enumerate(names, 1):
        print(f"  [{i}/{len(names)}] {name} ...", flush=True)
        cmd = [sys.executable, "-u", os.path.join(HERE, "run_benchmark_sweep.py"),
               "--state", STATE, "--providers", name, "--repeat", "1", "--budget", "86400"]
        if name in DISCLOSURE:
            cmd.append("--harness-arg=--strip-disclosure")
        # An unchecked exit code here is how a run that measured nothing still finishes by
        # printing a link to an unchanged page. Keep going -- one broken provider should not end
        # a ten-hour sweep -- but say so, and say so again in the summary.
        if subprocess.run(cmd, cwd=TALKITO).returncode:
            failed.append(name)
            print(f"  {name:<22} FAILED (see output above)", flush=True)
            continue
        print(report(name), flush=True)

    if failed:
        print(f"\n  {len(failed)} failed: {', '.join(failed)}")
    # Unflushed, this lands below the subprocess output it is meant to introduce.
    print(f"\n  {(time.time() - started) / 3600:.1f} h total. Rebuilding...\n", flush=True)
    # build_benchmark_page rewrites the table inside an existing page rather than generating one,
    # so a missing file is fatal and has to be said out loud. Left unchecked it fails, the export
    # runs anyway, and ships an archive with every sample and no page in it -- which is exactly
    # what the first end-to-end run produced.
    if not os.path.exists(PAGE_HTML):
        # A fresh clone has no page, and build_benchmark_page.py substitutes into an existing one
        # rather than generating it, so the first run of a new checkout would otherwise fail at
        # the very end with every measurement already paid for. Seed from the template instead.
        template = os.path.join(HERE, "page_template.html")
        if not os.path.exists(template):
            sys.exit(f"\n  no page at {PAGE_HTML} and no template at {template}\n"
                     f"  measurements are saved; rebuild with "
                     f"python3 tools/build_benchmark_page.py <page.html>")
        import shutil
        shutil.copy(template, PAGE_HTML)
        print(f"  seeded {os.path.basename(PAGE_HTML)} from template", flush=True)
    for step in (["build_benchmark_page.py", PAGE_HTML],
                 ["build_export.py", EXPORT_ZIP, PAGE_HTML]):
        done = subprocess.run([sys.executable, os.path.join(HERE, step[0]), *step[1:]], cwd=REPO)
        if done.returncode:
            sys.exit(f"\n  {step[0]} failed; measurements are saved and can be rebuilt with it")
    print(f"\n  open {PAGE_HTML}\n")


if __name__ == "__main__":
    main()
